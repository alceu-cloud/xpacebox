// Pure regression tests: no database, customer data or external sends.
const assert = require('node:assert/strict');
const m = require('../lib/xpace/report-metrics.ts');
const s = require('../lib/xpace/trial-schedule.ts');
const record = (id, changes = {}) => ({id,leadId:id,personId:null,on:'2026-08-31',startsAt:'19:00',kind:'NOVO',modality:'JAZZ',instructor:'PROFESSORA TESTE',attendance:'COMPARECEU',enrollment:'NAO_MATRICULOU',legacy:false,legacyMonth:null,...changes});
assert.equal(m.rate(0,0),null);
assert.equal(m.rate(1,2),50);
assert.equal(m.trialStats([]).conversionRate,null);
const rows = [record('1',{leadId:'same',enrollment:'MATRICULOU'}),record('2',{leadId:'same',enrollment:'PENDENTE'}),record('3',{attendance:'FALTOU',enrollment:'MATRICULOU'}),record('4',{attendance:'AGENDADO',enrollment:'NAO_INFORMADO'}),record('5',{personId:'person'}),record('6',{personId:'person'})];
const stats=m.trialStats(rows);
assert.equal(stats.appointments,6);
assert.equal(stats.leads,4,'Deduplicate by stable IDs, not by names');
assert.equal(stats.attended,4);
assert.equal(stats.absent,1);
assert.equal(stats.pendingAttendance,1);
assert.equal(stats.pendingEnrollment,2);
assert.equal(stats.attendedPending,1);
assert.equal(stats.enrollmentWithoutAttendance,1);
assert.equal(stats.conversionRate,50);
assert.equal(stats.modalityConversionRate,50,'Modality Excel rule counts all recorded enrollments / present');
assert.equal(stats.attendedConversionRate,33.33,'Professor rule excludes unresolved present enrollments');
assert.equal(stats.resolvedAttendanceRate,80);
assert.equal(stats.attendanceRate,66.67);
const report=m.buildTrialReport([...rows,record('cancelled',{attendance:'CANCELADO'}),record('outside',{on:'2026-09-01'})],'2026-08-01','2026-08-31');
assert.equal(report.stats.appointments,6);assert.equal(report.cancelled,1);
assert.equal(m.weekStart('2026-08-31'),'2026-08-30');
assert.equal(m.weekStart('2026-09-01'),'2026-08-30','A week crossing months is not duplicated');
assert.equal(m.monthSequence('2026-01-01','2027-12-31').length,24);
assert.equal(m.buildTrialReport([record('legacy',{legacy:true,legacyMonth:'q'})],'2026-08-01','2026-08-31').monthDifferences.length,1);
for(const [value,tone] of [[null,'neutral'],[54.99,'red'],[55,'amber'],[59.99,'amber'],[60,'green']])assert.equal(m.attendanceTone(value),tone);
for(const [n,sample] of [[4,'Baixa'],[5,'Média'],[9,'Média'],[10,'Alta']])assert.equal(m.professorSample(n),sample);
assert.equal(m.modalityAction({...stats,attended:9}),'Coletar dados');
assert.equal(m.modalityAction({...stats,attended:10,modalityConversionRate:50}),'Avaliar investimento');
assert.equal(m.professorAction({...stats,attendedKnown:4}),'Coletar dados');
assert.equal(m.professorAction({...stats,attendedKnown:5,attendedConversionRate:35}),'Manter e acompanhar');
assert.equal(m.professorAction({...stats,attendedKnown:5,attendedConversionRate:50}),'Compartilhar boas práticas');
assert.equal(s.scheduleAllowsTrial({allowLeads:true},{allowLeads:false}),true,'Current setting belongs to schedule');
assert.equal(s.scheduleAllowsTrial({allowLeads:false},{allowLeads:true}),false,'Explicit schedule prohibition wins');
assert.equal(s.scheduleAllowsTrial({}, {allowLeads:true}),false,'Settings object with no permission is not opt-in');
assert.equal(s.scheduleAllowsTrial(null,{allowLeads:true}),true,'Legacy groups fallback only when schedule settings are absent');
assert.equal(s.scheduleAllowsTrial(null,null),false);
assert.equal(s.trialScheduleSettings({leadWelcomeVideoUrl:'schedule-video'},{leadWelcomeVideoUrl:'old-video'}).leadWelcomeVideoUrl,'schedule-video');
console.log('PASS: report denominators, pending exclusions, stable identities, date grouping, actions and schedule permissions.');
