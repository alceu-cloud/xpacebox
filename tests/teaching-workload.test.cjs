const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const Module = require('node:module');
const filename = path.resolve(__dirname, '../lib/xpace/teaching-workload.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const moduleUnderTest = new Module(filename);
moduleUnderTest._compile(compiled, filename);
const { teachingOccurrences, lessonAmountCents, roomReservationQuote, intervalsOverlap } = moduleUnderTest.exports;

const schedule = { id: 'teens-monday', weekday: 1, startsAt: '19:00', endsAt: '20:00', startsOn: '2026-10-01' };
assert.deepEqual(teachingOccurrences('2026-10', [schedule]).map(x => x.scheduledOn), ['2026-10-05', '2026-10-12', '2026-10-19', '2026-10-26']);
assert.deepEqual(teachingOccurrences('2028-02', [{ ...schedule, weekday: 2 }]).map(x => x.scheduledOn), ['2028-02-01', '2028-02-08', '2028-02-15', '2028-02-22', '2028-02-29']);
assert.deepEqual(teachingOccurrences('2026-10', [{ ...schedule, startsOn: '2026-10-12', endsOn: '2026-10-19' }]).map(x => x.scheduledOn), ['2026-10-12', '2026-10-19']);
const shorter = teachingOccurrences('2026-10', [{ ...schedule, endsAt: '19:45' }]);
assert.equal(shorter[0].durationMinutes, 45);
assert.equal(shorter[0].lessonUnits, 1);
assert.equal(lessonAmountCents(shorter.length, 5000), 20000);
assert.equal(lessonAmountCents(4, 0), 0);
assert.throws(() => lessonAmountCents(1, null));
assert.throws(() => lessonAmountCents(1, Number.MAX_SAFE_INTEGER + 1));
assert.throws(() => teachingOccurrences('2026-13', [schedule]));
assert.throws(() => teachingOccurrences('2026-10', [{ ...schedule, startsOn: '2026-02-30' }]));
assert.throws(() => teachingOccurrences('2026-10', [schedule, schedule]));
assert.throws(() => teachingOccurrences('2026-10', [{ ...schedule, endsAt: '19:00' }]));

const startsAt = '2026-10-05T10:00:00-03:00';
assert.deepEqual(roomReservationQuote(startsAt, '2026-10-05T10:30:00-03:00', 3500), { durationMinutes: 30, hourlyRateCents: 3500, amountCents: 1750 });
assert.equal(roomReservationQuote(startsAt, '2026-10-05T11:30:00-03:00', 3500).amountCents, 5250);
assert.equal(roomReservationQuote(startsAt, '2026-10-05T13:45:00Z', 3500).amountCents, 2625);
assert.equal(roomReservationQuote(startsAt, '2026-10-05T10:01:00-03:00', 3500).amountCents, 58);
const oldQuote = roomReservationQuote(startsAt, '2026-10-05T11:00:00-03:00', 3500);
assert.equal(roomReservationQuote(startsAt, '2026-10-05T11:00:00-03:00', 4000).amountCents, 4000);
assert.equal(oldQuote.amountCents, 3500);
assert.throws(() => roomReservationQuote(startsAt, '2026-10-05T10:00:30-03:00', 3500));
assert.throws(() => roomReservationQuote('2026-10-05T10:00', '2026-10-05T11:00', 3500));
assert.throws(() => roomReservationQuote(startsAt, startsAt, 3500));
assert.throws(() => roomReservationQuote(startsAt, '2026-10-05T09:00:00-03:00', 3500));
assert.throws(() => roomReservationQuote(startsAt, '2026-10-05T11:00:00-03:00', -1));
const first = { startsAt, endsAt: '2026-10-05T11:00:00-03:00' };
assert.equal(intervalsOverlap(first, { startsAt: '2026-10-05T11:00:00-03:00', endsAt: '2026-10-05T12:00:00-03:00' }), false);
assert.equal(intervalsOverlap(first, { startsAt: '2026-10-05T10:30:00-03:00', endsAt: '2026-10-05T11:30:00-03:00' }), true);
assert.equal(intervalsOverlap(first, { startsAt: '2026-10-05T12:30:00Z', endsAt: '2026-10-05T13:30:00Z' }), true);
assert.equal(intervalsOverlap(first, first), true);
console.log('Teaching workload primitives: PASS (civil dates, leap year, schedule validity, lesson units, room pricing, snapshots and interval boundaries).');
